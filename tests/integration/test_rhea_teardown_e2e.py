"""End-to-end confirmation of the RHEA per-execution teardown via the CONTAINER backend.

Provisions rhea-server as a Docker CONTAINER (host-conda-independent — the only path that runs
tools on a host with a broken/missing conda), DOGFOODING the orchestrator's own production spec:
the docker-run command is generated by ``_make_rhea_container_spec`` + ``container_run_args`` (the
exact code apecx-mcp runs when ``APECX_RHEA_BACKEND=container``), so this test also guards that the
generated command is real. The ``live_rhea`` fixture (1) self-heals the DB schema via rhea's
self-migrating ``update_tools``, (2) reuses an already-healthy ``:3001`` or spawns the container
from the orchestrator spec, (3) waits for ``:3001`` healthy, and (4) SKIPS cleanly (never
flaky-FAILS) when Docker / the infra / the pre-built image is absent. Given a healthy rhea it
CONFIRMS the teardown: two real MUSCLE runs leave no net-new persisted ProxyStore Redis keys (the
per-call eviction holds), deciding on output VALUES not the run's status field (G127).

Requires the rhea-server image (auto-built by the orchestrator, or ``docker build``); skips with that hint when
absent. The first MUSCLE call cold-builds the per-tool conda env INSIDE the container (~15-20s for
MUSCLE); ``rhea_muscle_alignment``'s ``execution_timeout`` covers it.
"""

